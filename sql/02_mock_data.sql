-- 7. Sales Orders (2000 records - generated programmatically)
-- Since direct INSERT with complex logic is limited,
-- we'll use a stored procedure approach
-- ============================================

DELIMITER //

DROP PROCEDURE IF EXISTS generate_sales_orders//

CREATE PROCEDURE generate_sales_orders()
BEGIN
    DECLARE i INT DEFAULT 0;
    DECLARE j INT DEFAULT 0;
    DECLARE order_id BIGINT;
    DECLARE customer_region VARCHAR(50);
    DECLARE order_date DATE;
    DECLARE total_amount DECIMAL(14,2);
    DECLARE payment_st INT;
    DECLARE salesperson_id BIGINT;
    DECLARE order_no VARCHAR(32);
    DECLARE customer_id BIGINT;
    DECLARE items_count INT;

    -- Set initial auto_increment
    SET i = 0;

    WHILE i < 2000 DO
        -- Calculate order date (distributed across 8 months)
        SET order_date = DATE_ADD('2025-01-01', INTERVAL (i % 240) DAY);

        -- Select random customer
        SET customer_id = 1 + (i % 60);

        -- Get customer region
        SELECT region INTO customer_region FROM biz_customer WHERE id = customer_id;

        -- Calculate total amount based on customer level (A=3x C)
        SELECT CASE level
            WHEN 'A' THEN 20 + (i % 80)
            WHEN 'B' THEN 10 + (i % 40)
            ELSE 5 + (i % 20)
        END INTO total_amount FROM biz_customer WHERE id = customer_id;

        -- Payment status (15% unpaid, 25% partial, 60% paid)
        SET payment_st = CASE
            WHEN (i % 100) < 15 THEN 0
            WHEN (i % 100) < 40 THEN 1
            ELSE 2
        END;

        -- Salesperson (2-10 for sales department)
        SET salesperson_id = 3 + (i % 8);

        -- Generate order number
        SET order_no = CONCAT('SO', DATE_FORMAT(order_date, '%Y%m%d'), LPAD(i + 1, 4, '0'));

        -- Insert order
        INSERT INTO biz_sales_order (order_no, customer_id, order_date, total_amount, payment_status, salesperson_id, region)
        VALUES (order_no, customer_id, order_date, total_amount, payment_st, salesperson_id, customer_region);

        SET order_id = LAST_INSERT_ID();

        -- Generate 2-3 order items per order
        SET items_count = 2 + (i % 2);

        SET j = 0;
        WHILE j < items_count DO
            INSERT INTO biz_order_item (order_id, product_id, quantity, unit_price, subtotal)
            SELECT
                order_id,
                p.id,
                1 + (i + j) % 5,
                p.unit_price,
                (1 + (i + j) % 5) * p.unit_price
            FROM biz_product p
            WHERE p.id = 1 + ((i + j) % 20);
            SET j = j + 1;
        END WHILE;

        SET i = i + 1;
    END WHILE;
END//

DELIMITER ;

-- Execute the procedure to generate sales orders
CALL generate_sales_orders();

-- Drop the procedure after use
DROP PROCEDURE IF EXISTS generate_sales_orders;
